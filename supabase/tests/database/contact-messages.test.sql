CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;
BEGIN;
SELECT no_plan();
SELECT ok(NOT has_function_privilege('anon', 'public.guardar_mensaje_contacto(text,text,text,text)', 'EXECUTE'), 'anonymous callers cannot bypass server checks');
SELECT ok(NOT has_function_privilege('authenticated', 'public.guardar_mensaje_contacto(text,text,text,text)', 'EXECUTE'), 'authenticated callers cannot supply arbitrary IPs');
SELECT ok(NOT has_table_privilege('anon', 'public.mensajes_contacto', 'SELECT'), 'anonymous messages are private');
SELECT ok(NOT has_column_privilege('authenticated', 'public.mensajes_contacto', 'mensaje', 'UPDATE'), 'message content is immutable');
SELECT public.guardar_mensaje_contacto('Ana','ana@example.com','Hola',repeat('a',64)) FROM generate_series(1,5);
SELECT throws_ok($$SELECT public.guardar_mensaje_contacto('Ana','ana@example.com','Hola',repeat('a',64))$$, 'P0001', 'Rate limit exceeded', 'sixth submission rejected');
SELECT is((SELECT count(*)::integer FROM public.contact_rate_limits WHERE ip_hash=repeat('a',64)),5,'rejection does not consume another slot');
SELECT lives_ok($$SELECT public.guardar_mensaje_contacto('Ana','ana@example.com','Hola',repeat('b',64))$$,'another IP has its own window');
UPDATE public.contact_rate_limits SET accepted_at=now()-interval '16 minutes' WHERE ip_hash=repeat('a',64);
SELECT lives_ok($$SELECT public.guardar_mensaje_contacto('Ana','ana@example.com','Hola',repeat('a',64))$$,'expired slots are released');
SELECT throws_ok($$SELECT public.guardar_mensaje_contacto('','ana@example.com','Hola',repeat('c',64))$$,'23514',NULL,'database validates lengths');
SET LOCAL ROLE authenticated;
SELECT is((SELECT count(*)::integer FROM public.mensajes_contacto),0,'non-admin cannot read messages');
RESET ROLE;
SELECT * FROM finish();
ROLLBACK;
